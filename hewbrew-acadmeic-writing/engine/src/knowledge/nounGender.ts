export interface GenderGuess {
  gender: NounGender;
  /** האם ההכרעה נשענת על רשימה סגורה, על דפוס אמין, או על סיומת בלבד */
  confidence: 'lexicon' | 'pattern' | 'morphology';
  /** האם המילה ברבים */
  plural: boolean;
}

/** אותיות שימוש שאפשר להסיר לפני חיפוש בלקסיקון */
const PREFIX_RE = /^[הובכלמש]/;

/**
 * מנחש את מין שם העצם. מחזיר unknown כשאין די סימנים —
 * עדיף לא לדווח מאשר לדווח על סמך ניחוש.
 */
export function guessNounGender(word: string): GenderGuess {
  const bare = word.replace(PREFIX_RE, '');
  const candidates = word === bare ? [word] : [word, bare];

  for (const candidate of candidates) {
    if (DUAL_FEMININE.has(candidate)) {
      return { gender: 'f', confidence: 'lexicon', plural: true };
    }
    if (DUAL_MASCULINE.has(candidate)) {
      return { gender: 'm', confidence: 'lexicon', plural: true };
    }
    if (MASCULINE_PLURAL_OT.has(candidate)) {
      return { gender: 'm', confidence: 'lexicon', plural: true };
    }
    if (FEMININE_PLURAL_IM.has(candidate)) {
      return { gender: 'f', confidence: 'lexicon', plural: true };
    }
    if (MASCULINE_IRREGULAR.has(candidate)) {
      return { gender: 'm', confidence: 'lexicon', plural: false };
    }
    if (FEMININE_IRREGULAR.has(candidate)) {
      return { gender: 'f', confidence: 'lexicon', plural: false };
    }
    // ״אנשים״ הוא ריבוי של ״איש״ ולכן זכר, אף שאין לו יחיד בצורה זו
    if (candidate === 'אנשים') {
      return { gender: 'm', confidence: 'lexicon', plural: true };
    }
  }

  /*
   * דפוסים אמינים דיים כדי לתקן על פיהם:
   * ־ונות הוא ריבוי של שם זכר במשקל ־ון, ו־יות הוא ריבוי של שם נקבה ב־יה.
   */
  if (/ונות$/.test(word)) return { gender: 'm', confidence: 'pattern', plural: true };
  if (/יות$/.test(word)) return { gender: 'f', confidence: 'pattern', plural: true };
  if (/[ותי]יים$/.test(word) || /יים$/.test(word)) {
    // זוגי שאינו ברשימות — אין די מידע להכרעה
    return { gender: 'unknown', confidence: 'morphology', plural: true };
  }

  if (/ים$/.test(word)) return { gender: 'm', confidence: 'morphology', plural: true };
  if (/ות$/.test(word)) return { gender: 'f', confidence: 'morphology', plural: true };
  if (/[הת]$/.test(word)) return { gender: 'f', confidence: 'morphology', plural: false };

  return { gender: 'unknown', confidence: 'morphology', plural: false };
}
