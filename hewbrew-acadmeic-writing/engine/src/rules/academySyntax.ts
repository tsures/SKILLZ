/**
 * כללים ממדור ״תחביר וניסוח״ של האקדמיה ללשון העברית.
 *
 * המדור נקצר ב־`npm run harvest:syntax` ונקרא ערך־ערך. רוב הערכים בו
 * אינם פסיקה כלל — האקדמיה חוזרת ומדגישה שהיא ״ממעטת לפסוק בענייני
 * ניסוח וסגנון״ — ולכן נבחרו לכאן רק אלה שיש בהם קביעה מפורשת שצורה
 * מסוימת אינה תקינה, ושאפשר לזהות אותה בלי ניתוח תחבירי מלא.
 *
 * מה שנשאר בחוץ, ולמה
 * ────────────────────
 * ״בתור״ (האקדמיה לא עסקה ולא פסקה), ״החל מ־/החל ב־״ (יש מקום לשניהם),
 * ״הרבה אנשים/אנשים רבים״ (חמישה מבנים וכולם כשרים), ״יש/ישנם״ (הבדל
 * סגנוני), ״מצד אחד/מצד שני״, ״ו/או״, ״את אותו״, ״כמוך/כמותך״,
 * ״כאחד/כאחת״, ״הביתה/לבית״, ״בתי כנסת/בתי כנסיות״, ״שלוש/שלושה
 * רגלים״, ״מדובר על/מדובר ב״, ״עם זה/עם זאת״, וחזרה על מילת היחס.
 * כל אלה נבדקו מול המנוע והם עוברים נקיים — וכך צריך להיות. עורך
 * שמתקן אותם מתקן דבר שאינו שגוי.
 *
 * ״פסוקית זיקה ממשיכה״ (״עדכן את השרה שבירכה על ההחלטה״) היא אומנם
 * פסיקה מפורשת — ״ניסוחים מעין אלו אינם תקניים״ — אך זיהוי שלה מחייב
 * להבחין בין פסוקית לוואי לפסוקית שמוסרת אירוע חדש, וזו הבחנה סמנטית.
 * ״כְּשֶׁ־ ולא שֶׁ־״ מחייבת לדעת שהפסוקית היא פסוקית זמן. שתיהן לא כאן.
 */

import type { Rule } from '../text/diagnostics.js';
import { academy, regexRule } from './helpers.js';

const HEB = '\\u05D0-\\u05EA';
const HEB_ANY = '\\u05D0-\\u05EA\\u0591-\\u05C7';

/** שמות זמן שהצירוף שלהם עם ״הבא״ או ״שעברה״ מחייב מילת יחס */
const TIME_NOUNS = ['שבוע', 'חודש', 'שנה', 'יום', 'לילה', 'קיץ', 'חורף', 'סתיו', 'אביב'];

/** תוארי הזמן שנספחים אליהם */
const TIME_ADJECTIVES = ['הבא', 'הבאה', 'שעבר', 'שעברה', 'הקרוב', 'הקרובה', 'האחרון', 'האחרונה'];

/**
 * צורות ״אין״ הנוטות, לפי הגוף שהן אמורות להתאים לו.
 * ״את אינֵךְ״, ״אתה אינְךָ״, ״אני אינני״ — ההתאם הוא תחבירי.
 */
const EIN_BY_PRONOUN: Record<string, string> = {
  אני: 'אינני',
  אתה: 'אינך',
  את: 'אינך',
  אתם: 'אינכם',
  אתן: 'אינכן',
  אנחנו: 'איננו',
};

/** כל צורות ״אין״ הנוטות, לזיהוי הצורה השגויה שבאה אחרי כינוי הגוף */
const EIN_FORMS = [
  'אינני', 'איני', 'אינך', 'אינכם', 'אינכן', 'איננו', 'איננה', 'אינם', 'אינן', 'אינו',
];

export const academySyntaxRules: Rule[] = [
  regexRule({
    id: 'academy/approximation-doubled',
    category: 'common-errors',
    severity: 'error',
    title: 'כפל סימני קירוב — ״בערך כ־״',
    authority: academy(
      'תחביר וניסוח — ״בערך כ־״',
      'https://hebrew-academy.org.il/%d7%91%d7%a2%d7%a8%d7%9a-%d7%9b%d6%be/',
    ),
    // ״בערך״ ואחריה כ״ף הדמיון: שתיהן מציינות אומדן, ודי באחת
    pattern: new RegExp(`(?<![${HEB_ANY}])בערך\\s+(כ[${HEB}])`),
    message:
      '«בערך» והמילית «כ־» מציינות שתיהן קירוב, והבאתן זו לצד זו היא כפילות שאין לה יסוד.',
    suggestion: 'להשאיר אחת מהן בלבד',
    replacement: (m) => m[1],
    autoFixSafe: true,
  }),

  regexRule({
    id: 'academy/shenit-kol',
    category: 'common-errors',
    severity: 'error',
    title: '״שנית כול״ אינו צירוף',
    authority: academy(
      'תחביר וניסוח — ראשית כול אך לא ״שנית כול״',
      'https://hebrew-academy.org.il/%d7%a8%d7%90%d7%a9%d7%99%d7%aa-%d7%9b%d7%95%d7%9c-%d7%90%d7%9a-%d7%9c%d7%90-%d7%a9%d7%a0%d7%99%d7%aa-%d7%9b%d7%95%d7%9c/',
    ),
    /*
     * ״ראשית כול״ פירושו ״בראש הכול״, ולכן הוא צירוף בעל היגיון.
     * ״שנית״ שייכת לסדרה ראשית–שנית–שלישית, ובה אין ל״כול״ מקום:
     * מה שנאמר עליו ״שנית״ אינו שני לכל מה שאחריו.
     */
    pattern: new RegExp(`(?<![${HEB_ANY}])(שנית|שלישית|רביעית)\\s+(כול|כל)(?![${HEB_ANY}])`),
    message: (m) =>
      `«${m[1]} ${m[2]}» אינו צירוף. ״כול״ מצטרף ל״ראשית״ בלבד, שפירושה ״בראש הכול״; ` +
      `בסדרה ראשית–שנית–שלישית אין ל״כול״ מקום.`,
    suggestion: (m) => m[1],
    replacement: (m) => m[1],
    autoFixSafe: true,
  }),

  regexRule({
    id: 'academy/time-adverbial-preposition',
    category: 'syntax',
    severity: 'warning',
    title: 'מילת יחס בתיאור זמן יחסי',
    authority: academy(
      'תחביר וניסוח — שבוע הבא או בשבוע הבא',
      'https://hebrew-academy.org.il/%d7%a9%d7%91%d7%95%d7%a2-%d7%94%d7%91%d7%90-%d7%90%d7%95-%d7%91%d7%a9%d7%91%d7%95%d7%a2-%d7%94%d7%91%d7%90/',
    ),
    /*
     * ״ניפגש שבוע הבא״ — מילית היחס ב־ הושמטה, ותפקידה לציין שהעניין
     * מתרחש בתוך תקופת הזמן. הדרישה שהצירוף יופיע בלי אות שימוש לפניו
     * היא מה שמבחין בינו ובין ״השבוע הבא יהיה קשה״, שבו הצירוף הוא
     * הנושא של המשפט ואינו זקוק למילת יחס.
     */
    pattern: new RegExp(
      `(?<![${HEB_ANY}])(${TIME_NOUNS.join('|')})\\s+(${TIME_ADJECTIVES.join('|')})(?![${HEB_ANY}])`,
    ),
    message: (m) =>
      `בתיאור זמן יחסי באה מילית היחס ב־: «ב${m[1]} ${m[2]}» ולא «${m[0]}». ` +
      'תפקידה לציין שהדבר מתרחש בתוך תקופת הזמן.',
    suggestion: (m) => `ב${m[1]} ${m[2]}`,
    replacement: (m) => `ב${m[1]} ${m[2]}`,
    autoFixSafe: false,
  }),

  regexRule({
    id: 'academy/ein-person-agreement',
    category: 'syntax',
    severity: 'error',
    title: 'התאם הגוף בנטיית ״אין״',
    authority: academy(
      'תחביר וניסוח — את אינך או את איננה',
      'https://hebrew-academy.org.il/%d7%90%d7%aa-%d7%90%d7%99%d7%a0%d7%9a-%d7%90%d7%95-%d7%90%d7%aa-%d7%90%d7%99%d7%a0%d7%a0%d7%94/',
    ),
    /*
     * כשכינוי הגוף מפורש, נטיית ״אין״ מתאימה לו בהתאם תחבירי:
     * ״את אינֵךְ״, ״אתה אינְךָ״, ״אני אינני״ — ולא ״את איננה״.
     */
    pattern: new RegExp(
      `(?<![${HEB_ANY}])(${Object.keys(EIN_BY_PRONOUN).join('|')})\\s+(${EIN_FORMS.join('|')})(?![${HEB_ANY}])`,
    ),
    message: (m) => {
      const expected = EIN_BY_PRONOUN[m[1]];
      if (!expected || expected === m[2]) return null;
      return (
        `אחרי כינוי הגוף «${m[1]}» נטיית «אין» מתאימה לו בהתאם תחבירי: ` +
        `«${m[1]} ${expected}» ולא «${m[1]} ${m[2]}».`
      );
    },
    suggestion: (m) => `${m[1]} ${EIN_BY_PRONOUN[m[1]]}`,
    replacement: (m) => `${m[1]} ${EIN_BY_PRONOUN[m[1]]}`,
    autoFixSafe: true,
  }),
];
